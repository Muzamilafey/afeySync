// Regenerates src/openapi.routes.generated.ts from the Express route files mounted in src/app.ts.
// Usage: npm run openapi:routes   (hand-written entries in src/openapi.ts take precedence)
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const app = fs.readFileSync(path.join(root, 'src/app.ts'), 'utf8');

// import name(s) → { file, exported symbol }
const imports = new Map();
for (const m of app.matchAll(/^import (\w+|\{[^}]+\}) from '(\.\/modules\/[^']+)';/gm)) {
  const file = path.join(root, 'src', `${m[2].slice(2)}.ts`);
  if (m[1].startsWith('{')) for (const n of m[1].slice(1, -1).split(',').map((s) => s.trim()).filter(Boolean)) imports.set(n, { file, symbol: n });
  else imports.set(m[1], { file, symbol: 'default' });
}
// mounts: api.use('/prefix', name) or api.use(name)
const mounts = [];
for (const m of app.matchAll(/api\.use\((?:'([^']+)',\s*)?(\w+)\)/g)) if (imports.has(m[2])) mounts.push({ prefix: m[1] ?? '', name: m[2] });

const tagOf = (prefix, file) => {
  const seg = (prefix.split('/')[1] || path.basename(path.dirname(file))).replace(/-/g, ' ');
  if (['sha', 'dha', 'fhir', 'hr', 'opd', 'mch'].includes(seg)) return seg.toUpperCase();
  return seg.charAt(0).toUpperCase() + seg.slice(1);
};
const words = (p) => p.replace(/\{[^}]+\}|:\w+|\\\\?\$/g, '').split('/').filter(Boolean).join(' ').replace(/[-_]/g, ' ').trim();

const routes = {};
for (const { prefix, name } of mounts) {
  const { file, symbol } = imports.get(name);
  const src = fs.readFileSync(file, 'utf8');
  const varName = symbol === 'default' ? (/export default (\w+);/.exec(src)?.[1] ?? 'router') : symbol;
  const routerPerm = new RegExp(`${varName}\\.use\\(requirePermission\\('([^']+)'\\)`).exec(src)?.[1];
  const re = new RegExp(`${varName}\\.(get|post|put|patch|delete)\\(\\s*'([^']+)'([\\s\\S]{0,400}?)(?:h\\(|\\(req)`, 'g');
  for (const m of src.matchAll(re)) {
    const [, method, p, between] = m;
    const perms = [...between.matchAll(/require(?:Any)?Permission\(([^)]*)\)/g)].flatMap((x) => [...x[1].matchAll(/'([^']+)'/g)].map((y) => y[1]));
    const full = `/api/v1${prefix}${p === '/' ? '' : p}`.replace(/\\\\/g, '').replace(/:(\w+)/g, '{$1}').replace(/\/$/, '') || '/api/v1';
    const isPublic = /\/callbacks?\/\{token\}|\/c2b\/\{token\}/.test(full);
    const verb = { get: 'Get', post: 'Create/perform', put: 'Replace', patch: 'Update', delete: 'Delete' }[method];
    routes[full] ??= {};
    routes[full][method] = { summary: `${verb} ${words(`${prefix}${p}`) || 'resource'}`, tag: tagOf(prefix, file), ...(perms.length || routerPerm ? { permission: perms.length ? perms.join(' | ') : routerPerm } : {}), ...(isPublic ? { public: true } : {}) };
  }
}
const sorted = Object.fromEntries(Object.entries(routes).sort(([a], [b]) => a.localeCompare(b)));
const out = `// GENERATED by scripts/gen-openapi-routes.mjs — do not edit by hand.\nimport type { RouteDoc } from './openapi';\n\nexport const generatedRoutes: Record<string, Record<string, RouteDoc>> = ${JSON.stringify(sorted, null, 2)};\n`;
fs.writeFileSync(path.join(root, 'src/openapi.routes.generated.ts'), out);
console.log(`openapi: ${Object.keys(sorted).length} paths, ${Object.values(sorted).reduce((s, o) => s + Object.keys(o).length, 0)} operations`);
